import {create} from "zustand/react";
import {type FilterData, GroupableField, SortOrder, SortOrderDirection} from "../models/filters.ts";
import {persist} from "zustand/middleware";

export const useFilterStore = create<FilterData>()(
    persist((set) => ({
            filterSectionEnabled: true,
            selectedFilterPresetId: null,
            useAndFilteringStyle: false,
            isInstalled: false,
            isUninstalled: false,
            isHidden: false,
            isFavorite: false,
            name: null,
            version: null,
            releaseYear: null,
            genre: null,
            platform: null,
            publisher: null,
            developer: null,
            category: null,
            tag: null,
            series: null,
            region: null,
            source: null,
            ageRating: null,
            library: null,
            completionStatuses: null,
            feature: null,
            userScore: null,
            criticScore: null,
            communityScore: null,
            lastActivity: null,
            recentActivity: null,
            added: null,
            modified: null,
            playTime: null,
            installSize: null,
            sortingOrder: SortOrder.NAME,
            sortingOrderDirection: SortOrderDirection.ASCENDING,
            groupingOrder: GroupableField.NONE,
            actions: {
                clear: () => {
                    set({
                        useAndFilteringStyle: false,
                        selectedFilterPresetId: null,
                        isInstalled: false,
                        isUninstalled: false,
                        isHidden: false,
                        isFavorite: false,
                        name: null,
                        version: null,
                        releaseYear: null,
                        genre: null,
                        platform: null,
                        publisher: null,
                        developer: null,
                        category: null,
                        tag: null,
                        series: null,
                        region: null,
                        source: null,
                        ageRating: null,
                        library: null,
                        completionStatuses: null,
                        feature: null,
                        userScore: null,
                        criticScore: null,
                        communityScore: null,
                        lastActivity: null,
                        recentActivity: null,
                        added: null,
                        modified: null,
                        playTime: null,
                        installSize: null,
                        sortingOrder: SortOrder.NAME,
                        sortingOrderDirection: SortOrderDirection.ASCENDING,
                        groupingOrder: GroupableField.NONE,
                    })
                },
                setFilterSectionEnabled: (value) => set({filterSectionEnabled: value}),
                setSelectedFilterPresetId: (value) => set({selectedFilterPresetId: value}),
                setFromFilterPreset: (value) => {
                    const settings = value?.settings;
                    set({
                        useAndFilteringStyle: settings?.useAndFilteringStyle ?? false,
                        selectedFilterPresetId: value?.id,
                        isInstalled: settings?.isInstalled ?? false,
                        isUninstalled: settings?.isUninstalled ?? false,
                        isHidden: settings?.isHidden ?? false,
                        isFavorite: settings?.isFavorite ?? false,
                        name: settings?.name ?? null,
                        version: settings?.version ?? null,
                        releaseYear: settings?.releaseYear ?? null,
                        genre: settings?.genre ?? null,
                        platform: settings?.platform ?? null,
                        publisher: settings?.publisher ?? null,
                        developer: settings?.developer ?? null,
                        category: settings?.category ?? null,
                        tag: settings?.tag ?? null,
                        series: settings?.series ?? null,
                        region: settings?.region ?? null,
                        source: settings?.source ?? null,
                        ageRating: settings?.ageRating ?? null,
                        library: settings?.library ?? null,
                        completionStatuses: settings?.completionStatuses ?? null,
                        feature: settings?.feature ?? null,
                        userScore: settings?.userScore ?? null,
                        criticScore: settings?.criticScore ?? null,
                        communityScore: settings?.communityScore ?? null,
                        lastActivity: settings?.lastActivity ?? null,
                        recentActivity: settings?.recentActivity ?? null,
                        added: settings?.added ?? null,
                        modified: settings?.modified ?? null,
                        playTime: settings?.playTime ?? null,
                        installSize: settings?.installSize ?? null,
                        sortingOrder: value?.sortingOrder ?? SortOrder.NAME,
                        sortingOrderDirection: value?.sortingOrderDirection ?? SortOrderDirection.ASCENDING,
                        groupingOrder: value?.groupingOrder ?? GroupableField.NONE,
                    })
                },
                setUseAndFilteringStyle: (value) => set({useAndFilteringStyle: value, selectedFilterPresetId: null}),
                setIsInstalled: (value) => set({isInstalled: value, selectedFilterPresetId: null}),
                setIsUninstalled: (value) => set({isUninstalled: value, selectedFilterPresetId: null}),
                setIsHidden: (value) => set({isHidden: value, selectedFilterPresetId: null}),
                setIsFavorite: (value) => set({isFavorite: value, selectedFilterPresetId: null}),
                setName: (value) => set({name: value, selectedFilterPresetId: null}),
                setVersion: (value) => set({version: value, selectedFilterPresetId: null}),
                setReleaseYear: (value) => set({releaseYear: value, selectedFilterPresetId: null}),
                setGenre: (value) => set({genre: value, selectedFilterPresetId: null}),
                setPlatform: (value) => set({platform: value, selectedFilterPresetId: null}),
                setPublisher: (value) => set({publisher: value, selectedFilterPresetId: null}),
                setDeveloper: (value) => set({developer: value, selectedFilterPresetId: null}),
                setCategory: (value) => set({category: value, selectedFilterPresetId: null}),
                setTag: (value) => set({tag: value, selectedFilterPresetId: null}),
                setSeries: (value) => set({series: value, selectedFilterPresetId: null}),
                setRegion: (value) => set({region: value, selectedFilterPresetId: null}),
                setSource: (value) => set({source: value, selectedFilterPresetId: null}),
                setAgeRating: (value) => set({ageRating: value, selectedFilterPresetId: null}),
                setLibrary: (value) => set({library: value, selectedFilterPresetId: null}),
                setCompletionStatuses: (value) => set({completionStatuses: value, selectedFilterPresetId: null}),
                setFeature: (value) => set({feature: value, selectedFilterPresetId: null}),
                setUserScore: (value) => set({userScore: value, selectedFilterPresetId: null}),
                setCriticScore: (value) => set({criticScore: value, selectedFilterPresetId: null}),
                setCommunityScore: (value) => set({communityScore: value, selectedFilterPresetId: null}),
                setLastActivity: (value) => set({lastActivity: value, selectedFilterPresetId: null}),
                setRecentActivity: (value) => set({recentActivity: value, selectedFilterPresetId: null}),
                setAdded: (value) => set({added: value, selectedFilterPresetId: null}),
                setModified: (value) => set({modified: value, selectedFilterPresetId: null}),
                setPlayTime: (value) => set({playTime: value, selectedFilterPresetId: null}),
                setInstallSize: (value) => set({installSize: value, selectedFilterPresetId: null}),
                setSortingOrder: (value) => set({sortingOrder: value, selectedFilterPresetId: null}),
                setSortingOrderDirection: (value) => set({sortingOrderDirection: value, selectedFilterPresetId: null}),
                setGroupingOrder: (value) => set({groupingOrder: value, selectedFilterPresetId: null}),
            },
        }),
        {
            name: "filterStore",
            partialize: (state) => ({...state, actions: undefined}),
            merge: (persisted, current) => ({
                ...current,
                ...(persisted as Partial<FilterData>),
                actions: current.actions,
            }),
        }));